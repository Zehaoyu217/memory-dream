#!/usr/bin/env python3
"""Assemble online-build-bundle.md as ONE markdown: the hand-written body (phases, specs, exit conditions) plus
appendices copied verbatim from the repository (the skill text, the graph contract, the build guide, the prompts
and tuned tables, the eval record formats). `<--->` lines mark where the file may be split into several files;
each part stands on its own. Run it after changing any source it copies:  python3 tests/bundle_refresh.py
"""
import importlib.util
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUNDLE = ROOT / "online-build-bundle.md"
MARK = "<!-- appendices: generated by tests/bundle_refresh.py — everything below is copied from the repository; edit the sources, not this -->"
SPLIT = "<--->"


def shift_headings(text, by=1):
    """Demote markdown headings outside fenced code blocks so an embedded file nests under its appendix."""
    out, fence = [], None
    for ln in text.split("\n"):
        s = ln.strip()
        if fence:
            out.append(ln)
            if s.startswith(fence):
                fence = None
            continue
        if s.startswith("```") or s.startswith("~~~"):
            fence = s[:3]
            out.append(ln)
            continue
        m = re.match(r"^(#{1,6})\s", ln)
        out.append(("#" * by + ln) if m else ln)
    return "\n".join(out)


def fenced(text, lang=""):
    tick = "````" if "```" in text else "```"
    return f"{tick}{lang}\n{text.rstrip()}\n{tick}\n"


def constants():
    spec = importlib.util.spec_from_file_location("mem", ROOT / "skills/memory-dream/scripts/memory.py")
    mem = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mem)
    tables = {k: getattr(mem, k) for k in ("PREFIX_KIND", "AREA_KIND", "CC_KIND", "KINDS", "KIND_ORDER", "KIND_PARENT", "TYPE_PARENT", "SHAPES", "CONFLICT_KINDS",
                                           "DIGEST_KINDS", "ANSWER_KINDS", "WORK", "ROLE_OF",
                                           "CONFLICT_STOP", "GENERAL", "W", "PROMOTE", "BUDGET", "PROBATION_DAYS", "COMPLETE_MAX_NOTES",
                                           "COMPLETE_RATIO", "WEAK_SHARE", "TASTE_MAX", "TASTE_FLOOR", "NOTE_CAP", "NOTE_MAX_LINES", "WIDE",
                                           "CONFLICT_MAX", "DIGEST_MAX_LINES", "DIGEST_HEADS", "SCHEMA", "V") if hasattr(mem, k)}
    def js(v):
        if isinstance(v, (set, frozenset)):
            return sorted(v)
        if isinstance(v, dict):
            return {str(k): js(x) for k, x in v.items()}
        if isinstance(v, (list, tuple)):
            return [js(x) for x in v]
        return v
    return mem, {k: js(v) for k, v in tables.items()}


def main():
    text = BUNDLE.read_text()
    body = text.split("\n" + MARK)[0].rstrip() + "\n"
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    mem, tables = constants()
    parts = []
    parts.append(body)
    parts.append(f"\n{MARK}\n")
    parts.append(f"\n{SPLIT}\n\n## Appendix A — the contract surface, verbatim: `skills/memory-dream/SKILL.md` and the dreamer agent\n\n"
                 f"_Part 5 · copied at commit {sha}. Mode B workers write these files; Mode R workers check them. The skill text is what"
                 f" every agent reads, so its wording is part of the contract (achievement per word)._\n\n"
                 + fenced((ROOT / "skills/memory-dream/SKILL.md").read_text(), "markdown")
                 + "\n`skills/memory-dream/agents/memory-dreamer.md` (the helper agent for the no-API-key path):\n\n"
                 + fenced((ROOT / "skills/memory-dream/agents/memory-dreamer.md").read_text(), "markdown"))
    parts.append(f"\n{SPLIT}\n\n## Appendix B — the graph contract, verbatim: `.specs/memory-dream/CONTRACT.md`\n\n"
                 f"_Part 6 · copied at commit {sha}. Schema {tables.get('SCHEMA')}; `memory.py check` validates against it (A38)._\n\n"
                 + shift_headings((ROOT / ".specs/memory-dream/CONTRACT.md").read_text(), 1) + "\n")
    guide = (ROOT / "BUILD-GUIDE.md").read_text()
    guide = guide[guide.index("## 3. The design in one page"):]
    parts.append(f"\n{SPLIT}\n\n## Appendix C — the build guide, verbatim: `BUILD-GUIDE.md` §3–§10\n\n"
                 f"_Part 7 · copied at commit {sha}. The design in one page, the repository layout, every module's algorithm"
                 f" (§5: notes and SKILL.md, scan, note facts, the graph's two halves, the dreamer, answering, big memories,"
                 f" the contract, the viewer), the tests, how to reproduce the evaluations, the numbers to expect, the pitfalls"
                 f" and the known limits. Phase briefs point here as \"Appendix C §n\"._\n\n" + shift_headings(guide, 1) + "\n")
    d = [f"\n{SPLIT}\n\n## Appendix D — prompts, seeds and tuned tables, verbatim from `memory.py`\n\n"
         f"_Part 8 · extracted at commit {sha} by importing the script. The dreamer's two prompts, the seed vocabulary"
         f" (`EDGES.md`), the packs for other domains, the headers of the user-owned files, and every tuned number with its"
         f" name. A rebuild reproduces these exactly; the measurements in RESULTS.md set them._\n\n"]
    d.append("### D.1 `EXTRACT` — the per-note prompt: fixed guidance, then `KINDS:`, `TYPES:`, `EDGES:` and `KNOWN:` from the registries (the static part is cached), then `NOTE`\n\n" + fenced(mem.EXTRACT))
    d.append("\n### D.2 `REVIEW` — the one-call review (entity pairs, labels over the bar, conflicts, type words over the bar)\n\n" + fenced(mem.REVIEW))
    d.append("\n### D.3 `EDGES_SEED` — `memory/EDGES.md` as first written (relation types, with `shape:`)\n\n" + fenced(mem.EDGES_SEED, "markdown"))
    d.append("\n### D.3b `KINDS_SEED` — `memory/KINDS.md` as first written (kinds of note: prefix, area, family, role, digest, conflicts, answers)\n\n" + fenced(mem.KINDS_SEED, "markdown"))
    d.append("\n### D.3c `TYPES_SEED` — `memory/TYPES.md` as first written (types of thing: aliases, family, not, drop)\n\n" + fenced(mem.TYPES_SEED, "markdown"))
    d.append("\n### D.4 `PACKS`, `KIND_PACKS`, `TYPE_PACKS` — the lines a `pack: software|research|ops` adds to each registry\n\n"
             + fenced(json.dumps({"EDGES.md": mem.PACKS, "KINDS.md": mem.KIND_PACKS, "TYPES.md": mem.TYPE_PACKS}, indent=1, ensure_ascii=False), "json"))
    d.append("\n### D.5 Headers of `ALIASES.md` and `CONFLICTS.md`\n\n" + fenced(mem.ALIASES_HEAD if isinstance(mem.ALIASES_HEAD, str) else "".join(mem.ALIASES_HEAD), "markdown")
             + "\n" + fenced(mem.CONFLICTS_HEAD if isinstance(mem.CONFLICTS_HEAD, str) else "".join(mem.CONFLICTS_HEAD), "markdown"))
    d.append("\n### D.6 Tuned tables and constants (`W` is `rank`/`route`; the rest are named where they are used)\n\n" + fenced(json.dumps(tables, indent=1, ensure_ascii=False), "json"))
    parts.append("".join(d))
    e = f"""
{SPLIT}

## Appendix E — evaluation record formats

_Part 9 · the shapes `eval/` reads and writes, so a rebuilt eval can be compared line for line with the reference._

- **Question** (`eval/questions/*.jsonl`, one JSON object per line): `type` (lookup · lineage · dependency · current ·
  numeric · why · preference · reporting · term · correction · howto · qa), `q` (the question), `a` (the reference
  answer the judge grades against), `notes` (gold note paths; with `--must` the superseded ones count as history),
  `bundle` (the area or question file it came from), optional `nums` (numbers the answer must contain).
- **Taste task** (`eval/taste/tasks.jsonl`): `type` (taste-named · taste-implicit), `q` (the task), `a` (empty),
  `notes` (the preference and rule notes that should come along).
- **Batch** (`eval/agent/batches/<name>.jsonl`): ten question lines, made by `eval/agent/make_batches.py` (seeded).
- **Agent answer file** (`eval/agent/runs/<cell>-<arm>-<batch>.md`): sections `## Q1` … `## Q10`, each an answer,
  a `Sources:` line and `Tool calls for this question: n`; last lines `Total tool calls in this task: n` and
  `Minutes spent: n`.
- **Judge** (`eval/judge.py <batch> <answers.md>` → `eval/agent/judge-<cell>-<arm>-<batch>.json`):
  `{{"<answers.md>": {{"correct": n, "partial": n, "wrong": n, "verdicts": {{"Q1": {{"v": "correct|partial|wrong", "why": "…"}}}}}}}}`.
- **Usage** (`eval/a21/extract.py <out_dir> name=<transcript.jsonl>` → one line in `eval/agent/usage-<cell>.jsonl`):
  `{{"run", "tool_calls", "requests", "input", "cache_read", "cache_write", "output", "total"}}`; cost units weight
  fresh input 1, cache read 0.1, cache write 1.25, output 5.
- **Harness** (`eval/agent/harness.json`): `{{"<run>": {{"tokens", "tool_uses", "ms"}}}}` from the subagent notifications.
- **Summary** (`eval/agent/summarize.py` → `summary.json`): per cell `runs, questions, correct, partial, wrong,
  tool_calls, requests, processed_tokens, cost_units, secs`, and `<size>-mem/grep` ratios.
- **Retrieval** (`eval/retrieval.py <memory> <questions…> [--must]`): one JSON line `{{"questions", "note_recall",
  "num_recall", "precision", "full_note_hit", "chars_per_batch", "chars_per_q", "secs_per_batch"}}` after the
  `  miss …` lines. **Adversarial** (`eval/adversarial.py <memory> <questions…> [--index-world <root>]`): JSON with
  `stale`, `scatter`, `absence` and, with an index world, `alias`.
- **Dreamer cost log** (`DREAM_COST_LOG=<file>` with `tests/haiku_cmd.py`): one JSON line per call `{{"kind":
  "extract|review", "cost", "ms", "in", "fresh", "cached", "cache_write", "out", "static", "error"}}`.
"""
    parts.append(e)
    BUNDLE.write_text("".join(parts).rstrip() + "\n")
    out = BUNDLE.read_text()
    print(f"bundle: {len(out.splitlines())} lines · {out.count(SPLIT)} split markers · appendices from commit {sha}")


if __name__ == "__main__":
    main()
